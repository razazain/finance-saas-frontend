import { useEffect, useState } from "react";
import { Lightbulb, Sparkles, TrendingUp } from "lucide-react";
import { Badge, Card, Notice, PageHeader, StatCard } from "@/components/ui";
import { financeApi } from "@/lib/api/services";
import { getApiErrorMessage } from "@/lib/api/client";
import { useApp } from "@/context/AppContext";
import { money } from "@/lib/utils";

export default function InsightsPage() {
  const { data } = useApp();
  const [result, setResult] = useState<any>(null);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(true);
  useEffect(() => {
    let active = true;
    financeApi
      .insights()
      .then((r) => {
        if (active) setResult(r);
      })
      .catch((e) => {
        if (active) setError(getApiErrorMessage(e));
      })
      .finally(() => {
        if (active) setBusy(false);
      });
    return () => {
      active = false;
    };
  }, []);
  const summary =
    result?.summary ?? "No financial insight summary is available yet.";
  const insights = Array.isArray(result?.insights) ? result.insights : [];
  return (
    <div className="page-stack">
      <PageHeader
        title="Financial insights"
        description="Insights are generated by the Munshee backend from your recorded financial activity."
      />
      <div className="insights-intro">
        <div className="insights-intro-icon">
          <Sparkles size={22} />
        </div>
        <div>
          <h2>Your business at a glance</h2>
          <p>
            These observations come from the server's current financial records,
            not seeded demo values.
          </p>
        </div>
        <Badge tone="info">
          {result?.generatedBy === "deterministic-financial-insights"
            ? "Backend insights"
            : "Live data"}
        </Badge>
      </div>
      <div className="stats-grid three">
        <StatCard
          label="Income records"
          value={String(
            data.transactions.filter(
              (t) => t.status === "Posted" && t.type === "Income",
            ).length,
          )}
          detail="Loaded from the transaction API"
          tone="green"
        />
        <StatCard
          label="Expense records"
          value={String(
            data.transactions.filter(
              (t) => t.status === "Posted" && t.type === "Expense",
            ).length,
          )}
          detail="Loaded from the transaction API"
          tone="amber"
        />
        <StatCard
          label="Net posted activity"
          value={money(
            data.transactions
              .filter((t) => t.status === "Posted" && t.type === "Income")
              .reduce((s, t) => s + Number(t.amount), 0) -
              data.transactions
                .filter((t) => t.status === "Posted" && t.type === "Expense")
                .reduce((s, t) => s + Number(t.amount), 0),
            data.settings.currency,
            0,
          )}
          detail="Calculated from fetched records"
          tone="blue"
        />
      </div>
      <Card className="form-card">
        <div className="card-heading">
          <div>
            <h2>Backend summary</h2>
            <p>Server-generated financial overview</p>
          </div>
          <TrendingUp size={19} />
        </div>
        {busy ? (
          <p>Loading insights…</p>
        ) : error ? (
          <Notice tone="danger" title="Unable to load insights">
            {error}
          </Notice>
        ) : (
          <>
            <p>{summary}</p>
            <div className="insight-grid">
              {insights.map((text: string, index: number) => (
                <Card className="insight-card" key={`${index}-${text}`}>
                  <div className="insight-card-top">
                    <span className="insight-icon">
                      <Lightbulb size={18} />
                    </span>
                    <Badge tone="info">Observation {index + 1}</Badge>
                  </div>
                  <p>{text}</p>
                </Card>
              ))}
            </div>
          </>
        )}
      </Card>
      <Notice tone="warning" title="Important">
        These are bookkeeping observations, not tax or investment advice. Review
        source records before acting on a financial insight.
      </Notice>
    </div>
  );
}
